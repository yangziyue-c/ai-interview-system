#   llm_first  听 LLM；LLM 没判出来（超时/解析失败）才退回 reranker   ← 默认
#   agree      一致才用；不一致取**较浅**那个（拿不准就别往深里挖）
#   deepest    取较深那个（更爱追问，宁可多问不少问）
#   reranker   只用 reranker（= 关掉判档；留给 A/B 对照用的那一臂）
JUDGE_FUSE = os.environ.get("A11_JUDGE_FUSE", "llm_first")
