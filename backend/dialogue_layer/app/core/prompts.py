# 换题时面试官说的那句过场话。**固定文本，不过 LLM**（见 session._swap_round）。
# 这是一条控制流路径上的旁白：让 LLM 来说，它多半会顺势追问一句，而
# 「别再问这道题了」正是这一步要做的事。代价是这句话不可变、可被考生背下来 ——
# 但换题上限是一场一次，背下来也只赚一道题。
SWAP_LINE = "好，这道题我们先放一放，换一个方向继续。"

# 追问素材块（$hint 是主库给的追问文本或降级策略）
HINT_BLOCK = Template("""
【可参考的追问方向】（用你自己的话问，不要照念；只作方向参考）
$hint""")

# 要追问、但主库没给素材
HINT_BLOCK_EMPTY = "\n（没有可参考的追问素材，用你自己的话问。）"

# 本轮收尾（action == close）
#
# ⚠️ 这里**绝对不能**复用 HINT_BLOCK_EMPTY。那句"用你自己的话问"和
#    ACTION_DESC["close"] 的"不要自己出下一题"直接打架，模型在矛盾指令之间
#    会倾向去提问 —— 现象就是收尾那轮又追了一个问题，然后前端 500ms 后
#    自动出下一题，看起来像"连着追问又问下一题"。
HINT_BLOCK_CLOSE = "\n（本轮不再提问。只输出收尾点评，**不要出现任何问句**。）"


# ============================================================
# 深挖方向 / RAG 参考 —— 只在 L1、L2 轮注入
# ============================================================
# ⚠️⚠️ 读到这里的人请注意：**收尾轮（action == "close"）绝不能注入下面任何一块。**
#
# 这不是谨慎，是踩过的坑。四条独立理由：
#
#   ① 杠杆在**消息列表**，不在 system。上面 CLOSE_DIRECTIVE 那段实测已经指明：
#      改措辞（system）出问句 10/10、强约束 4/10、降温度 8/10（更糟）、
#      system 换收尾专用 prompt 4/10，而末尾加一条临时旁白（消息列表）是 0/10。
#      **system 是这一场里最弱的杠杆** —— 往 system 里塞与收尾相反的内容，
#      等于在最不该用力的那一层用力。
#   ② 深挖方向比 HINT_BLOCK_EMPTY 更危险。后者只是**授予了提问的许可**
#      （"没有素材，用你自己的话问"），就已经和 ACTION_DESC["close"] 打架；
#      前者不但给许可，还**直接告诉它问什么**。同一个冲突的加强版。
#   ③ RAG 片段**本身就是别的题目文本**（含答题要点、示例话术）。在唯一一个
#      "提问是最高概率续写"的轮次里主动递上提问素材，等于把一个已知 0/10 的
#      机制往 10/10 推。
#   ④ 语义上是死信息。close 意味着本轮结束，此刻给"可拓展的关联方向"没有任何
#      消费者 —— 纯风险，零收益。
#
# 同样的理由适用于 action == "degrade"：ACTION_DESC["degrade"] 要的是
# **收拢**（给点方向引导他继续想），灌"可拓展的关联方向"是把面试官推向深挖，
# 与动作指令反向。
#
# 所以 session.py 里的门控是 `action in ("L1", "L2")`，并且有冒烟断言守着
# （smoke_test.py 的 close/degrade 轮 system 断言）。要改这个门控，
# 先把上面四条推翻。
DEEPEN_BLOCK = Template("""
【可拓展的关联方向】（只是方向，**不要照念**，也**不要变成一道新题**）
$directions""")

RAG_BLOCK = Template("""
【同岗位参考片段】（**只作背景参考**：不要照念、不要向考生透露、不要拿来出新题）
$refs""")

# 不注入时用的**空串** —— 刻意不是一句"（没有可参考的方向）"之类的提示句。
# 这是「开关全关时 system 逐字节不变」的保证：HINT_BLOCK_EMPTY 的教训正是
# 一句看似无害的提示句会和动作指令打架。只要这里的值是空串，
# 关掉 KG 与 RAG 之后送进模型的 system 就和加这两个功能之前一模一样。
DEEPEN_BLOCK_EMPTY = ""
RAG_BLOCK_EMPTY = ""

# 收尾轮的**临时旁白**：只加在这一次请求的消息列表末尾，**不写进 transcript**。
#
# 为什么需要它（实测数据，不是拍脑袋）：
#   收尾轮光靠 system 里的约束压不住 —— 模型上一句自己就是个问句，
#   上下文里概率最高的续写就是"再问一句"。同一个 transcript 各跑 10 次：
#     · 现状（只改措辞）：           出问句 10/10
#     · 强约束措辞（要求禁止问号）：   出问句  4/10
#     · 强约束 + temp 降到 0.2：     出问句  8/10   ← 降温度**反而更糟**
#     · system 换成收尾专用 prompt：  出问句  4/10
#     · 末尾加这条临时旁白：          出问句  0/10   ← 唯一压得住的
#   低温度之所以更糟：提问是这个上下文里概率最高的续写，温度越低越锁死它。
#   而"最近的 user 轮"权重最高，所以把收尾指令放在最后一条 user 消息里才管用。
#   同时它也**不影响**正常追问轮（L2 回归：10/10 仍然正常提问）。
CLOSE_DIRECTIVE = ("（系统旁白：本轮到此结束。请只输出 1~2 句收尾点评，"
                   "并说一句过渡到下一个话题。不要再提出任何问题。）")


